import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('../src/email-auth.js',import.meta.url),'utf8');
const {createEmailSender}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
let clock=1000,calls=0,resolve;
const auth={signInWithOtp:()=>{calls++;return new Promise(r=>resolve=r);}};
const sender=createEmailSender(auth,storage,()=>clock);
const pending=sender.send('buyer@example.com',{});
await assert.rejects(()=>sender.send('buyer@example.com',{}),/already being processed/);assert.equal(calls,1);
resolve({error:null});await pending;assert.equal(sender.remaining(),60);
await assert.rejects(()=>sender.send('buyer@example.com',{}),/Please wait/);assert.equal(calls,1);
const reloaded=createEmailSender(auth,storage,()=>clock);assert.equal(reloaded.remaining(),60,'Cooldown survives reload');
clock+=60001;
const rate=createEmailSender({signInWithOtp:async()=>({error:{status:429,code:'over_email_send_rate_limit',message:'email rate limit exceeded'}})},storage,()=>clock);
await assert.rejects(()=>rate.send('buyer@example.com',{}),err=>err.code==='email_limit'&&/new email was not sent/.test(err.message));assert.equal(rate.remaining(),60);
clock+=60001;
await assert.rejects(()=>sender.send('owner@demo.com',{}),/Demo accounts/);assert.equal(calls,1);
const unauthorized=createEmailSender({signInWithOtp:async()=>({error:{code:'email_address_not_authorized'}})},storage,()=>clock);
await assert.rejects(()=>unauthorized.send('buyer@example.com',{}),/custom SMTP/);
console.log('PASS: duplicate requests blocked, resend cooldown persists, 429 explained without fake reset promises, demo emails rejected, SMTP recipient errors explained.');
